void joystick_north() { 
    // Moving up the menu
    // Changes current state upwards and updates screen pointer position
    switch (currentState) {
        case SONG_1:
            currentState = SONG_3;
            y_pos_pointer = 32;
            break;
        case SONG_2:
            currentState = SONG_1;
            y_pos_pointer = 0;
            break;
        case SONG_3:
            currentState = SONG_2;
            y_pos_pointer = 17;
            break;
    }
    start_menu(); // refresh screen with new pointer position
}

void joystick_south() {
    // Moving down the menu
    // Changes current state downwards and updates screen pointer position
    switch (currentState) {
        case SONG_1:
            currentState = SONG_2;
            y_pos_pointer = 17;
            break;
        case SONG_2:
            currentState = SONG_3;
            y_pos_pointer = 32;
            break;
        case SONG_3:
            currentState = SONG_1;
            y_pos_pointer = 0;
            break;
    }
    start_menu(); // refresh screen with new pointer position
}

