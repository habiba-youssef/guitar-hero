int main() {
    lcd.init(LPH7366_1);
    lcd.setContrast(0.8);      //set contrast to 55%
    lcd.setBrightness(0.4);
    joystick.init();
    pushbutton.mode(PullUp);

    main_menu();
    while (1){
        // check direction of joystick
        if(joystick.get_direction() == N){
            y_pos_pointer = 32; 
            main_menu();
            if (pushbutton.read() == 0){ // if menu item is selected display next screen
                start_menu();
                while(1) {
                    // depending on joystick direction choose which FSM function to jump to
                    if (joystick.get_direction() == N) { 
                        joystick_north();
                        ThisThread::sleep_for(1s);
                        if (pushbutton.read() == 0){ // if menu item is selected display next screen
                            select();
                        }
                    } 
                    else if (joystick.get_direction() == S) {
                        joystick_south();
                        ThisThread::sleep_for(1s);
                        if (pushbutton.read() == 0){
                            select();
                        }
                    }
                }
                break;
            }
        }
        else if(joystick.get_direction() == S){
            y_pos_pointer = 40;
            main_menu(); 
            if (pushbutton.read() == 0){
                tutorial(); // start 'How to Play' if selected 
            }
        }    
    }    
}

